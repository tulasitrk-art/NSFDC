# Helper to deep copy and merge
def deep_merge(base, overrides):
    res = {}
    for k, v in base.items():
        if isinstance(v, dict):
            res[k] = deep_merge(v, overrides.get(k, {}))
        else:
            res[k] = overrides.get(k, v)
    for k, v in overrides.items():
        if k not in res:
            res[k] = v
    return res

